#!/usr/bin/env python3
"""Regenerate the unit part of the sidebar in _quarto.yml from plan/units.md.

Only units whose <slug>/lec.qmd exists are listed. Demo entries come from
plan/demo-labels.tsv (slug<TAB>label). The block between the markers
'# BEGIN UNITS' and '# END UNITS' is replaced.
Run from the project root:  python3 plan/sidebar.py
"""
import os, re
rows = []
for line in open('plan/units.md'):
    m = re.match(r'\| (\d+) \| `([a-z0-9-]+)` \| (.*?) \| (Part \d+): (.*?) \|', line)
    if m: rows.append((int(m.group(1)), m.group(2), m.group(3), m.group(4), m.group(5)))
labels = dict(l.rstrip('\n').split('\t') for l in open('plan/demo-labels.tsv') if '\t' in l)
out, cur = [], None
q = lambda t: '"' + t.replace('"', '\\"') + '"'
for n, slug, title, part, pname in sorted(rows):
    if not os.path.exists(f'{slug}/lec.qmd'): continue
    if part != cur:
        cur = part
        out += [f'      - section: {q(f"{part}: {pname}")}', '        contents:']
    out += [f'          - section: {q(title)}', '            contents:',
            '              - text: "Lecture (slides)"', f'                href: {slug}/lec.qmd']
    if os.path.exists(f'{slug}/quiz.qmd'):
        out += ['              - text: "Quiz"', f'                href: {slug}/quiz.qmd']
    if os.path.exists(f'{slug}/exercise.qmd'):
        out += ['              - text: "Exercise"', f'                href: {slug}/exercise.qmd']
    if slug in labels:
        out += [f'              - text: {q("Demo: " + labels[slug])}', f'                href: {slug}/exercise.qmd#explore']
s = open('_quarto.yml').read()
block = '      # BEGIN UNITS (generated by plan/sidebar.py — do not edit by hand)\n' + '\n'.join(out) + '\n      # END UNITS\n'
s = re.sub(r'      # BEGIN UNITS.*?# END UNITS\n', block, s, flags=re.S)
open('_quarto.yml', 'w').write(s)
print(f'{sum(1 for l in out if "Lecture" in l)} units in sidebar')
